import test from "node:test";
import assert from "node:assert/strict";
import { convertHtaccess } from "../../src/lib/network/htaccessConvert.ts";

test("converts ErrorDocument, Header set and DirectoryIndex", () => {
  const { nginx, warnings } = convertHtaccess(
    [
      "ErrorDocument 404 /404.html",
      'Header always set X-Frame-Options "SAMEORIGIN"',
      "DirectoryIndex index.html index.php",
    ].join("\n")
  );
  assert.match(nginx, /error_page 404 \/404\.html;/);
  assert.match(nginx, /add_header X-Frame-Options "SAMEORIGIN" always;/);
  assert.match(nginx, /index index\.html index\.php;/);
  assert.equal(warnings.length, 0);
});

test("converts RewriteRule with redirect flags into return", () => {
  const { nginx } = convertHtaccess("RewriteRule ^old/(.*)$ /new/$1 [R=301,L]");
  assert.match(nginx, /if \(\$request_uri ~\* "\^old\/\(\.\*\)\$"\) \{ return 301 \/new\/\$1; \}/);
});

test("RewriteCond lines become comments and are flagged", () => {
  const { nginx, warnings } = convertHtaccess(
    ["RewriteCond %{HTTPS} !=on", "RewriteRule ^(.*)$ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]"].join("\n")
  );
  assert.match(nginx, /# RewriteCond/);
  assert.ok(warnings.some((w) => /RewriteCond/.test(w.reason)));
});

test("unrecognized directives are preserved as comments with warnings", () => {
  const { nginx, warnings, convertedCount } = convertHtaccess("SomeUnknownDirective foo bar");
  assert.match(nginx, /# UNCONVERTED: SomeUnknownDirective foo bar/);
  assert.equal(warnings.length, 1);
  assert.equal(convertedCount, 0);
});

test("allow/deny and Require ip map to nginx access directives", () => {
  const { nginx } = convertHtaccess(["Require ip 10.0.0.0/8", "deny from all"].join("\n"));
  assert.match(nginx, /allow 10\.0\.0\.0\/8;/);
  assert.match(nginx, /deny all;/);
});

test("comments pass through and empty input yields header-only output", () => {
  const { nginx } = convertHtaccess("# my comment\n");
  assert.match(nginx, /# my comment/);
  const empty = convertHtaccess("");
  assert.match(empty.nginx, /Generated by Build-Better/);
  assert.equal(empty.convertedCount, 0);
});
