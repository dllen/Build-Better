// ============ 派生工具函数 ============

const CATEGORY_ORDER = new Map(CATEGORIES.map((c) => [c.id, c.order]));

export function toolsByCategory(cat: CategoryId): ToolMeta[] {
  return TOOL_REGISTRY.filter((t) => t.category === cat);
}

/** 按分类 order 分组，跳过空分类 */
export function groupedTools(): { category: CategoryMeta; tools: ToolMeta[] }[] {
  return CATEGORIES.map((category) => ({
    category,
    tools: toolsByCategory(category.id),
  })).filter((g) => g.tools.length > 0);
}

export function popularTools(): ToolMeta[] {
  return TOOL_REGISTRY.filter((t) => t.popular);
}

export function recentTools(): ToolMeta[] {
  return TOOL_REGISTRY.filter((t) => t.isNew);
}

export function categoryOrder(cat: CategoryId): number {
  return CATEGORY_ORDER.get(cat) ?? 999;
}
