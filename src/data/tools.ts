export interface ToolMeta {
  id: string;
  /** 扁平 URL，如 /base64 */
  path: string;
  category: CategoryId;
  icon: LucideIcon;
  /** tailwind 文本色，如 text-blue-600 */
  color: string;
  /** tailwind 背景色，如 bg-blue-100 */
  bgColor: string;
  /** 名称兜底文案（也是 i18n fallback） */
  name: string;
  /** 描述兜底文案 */
  description: string;
  /** i18n key（可选，存在则组件内 t(nameKey, name)） */
  nameKey?: string;
  descKey?: string;
  /** 搜索增强关键词 */
  keywords?: string[];
  /** 热门（进入 Popular 区） */
  popular?: boolean;
  /** 最近新增（进入 Recently Added 区） */
  isNew?: boolean;
}

export interface CategoryMeta {
  id: CategoryId;
  /** i18n label key，如 categories.developer */
  labelKey: string;
  icon: LucideIcon;
  order: number;
}

